  /* Look at the flat sheet from an angle, light it, and let the far edge fall out of focus. */
  function finish(flatCv, seed) {
    const r = rng((seed || 3) * 7 + 11);
    const W = 1200, H = 900;
    const jx = (r() - .5) * 60, jy = (r() - .5) * 60;
    const corners = [
      [110 + jx, 60 + jy],
      [1400 + jx, 150 - jy],
      [1420 + jx, 1000 - jy],
      [90 + jx, 1080 + jy]
    ];
    const warped = Media.deskew(flatCv, corners, 1500);
    const cv = document.createElement('canvas');
    cv.width = W; cv.height = H;
    const c = cv.getContext('2d', { willReadFrequently: true });
    c.drawImage(warped, 0, 0, W, H);

    // depth of field: the far side of the frame goes soft
    try {
      const soft = document.createElement('canvas');
      soft.width = W; soft.height = H;
      const sc = soft.getContext('2d');
      sc.filter = 'blur(5px)';
      sc.drawImage(cv, 0, 0);
      sc.filter = 'none';
      sc.globalCompositeOperation = 'destination-in';
      const mg = sc.createLinearGradient(W, 0, W * .25, H * .8);
      mg.addColorStop(0, 'rgba(0,0,0,1)');
      mg.addColorStop(.45, 'rgba(0,0,0,.55)');
      mg.addColorStop(1, 'rgba(0,0,0,0)');
      sc.fillStyle = mg;
      sc.fillRect(0, 0, W, H);
      c.drawImage(soft, 0, 0);
    } catch (e) {}

    // daylight from one side, cool shadow on the other
    c.globalCompositeOperation = 'overlay';
    const lg = c.createLinearGradient(0, 0, W, H);
    lg.addColorStop(0, 'rgba(255,236,196,.30)');
    lg.addColorStop(.55, 'rgba(255,255,255,0)');
    lg.addColorStop(1, 'rgba(40,58,86,.28)');
    c.fillStyle = lg;
    c.fillRect(0, 0, W, H);
    c.globalCompositeOperation = 'source-over';

    grain(c, W, H, 15, (seed || 3) * 31 + 5);
    vignette(c, W, H, .26);
    return cv;
  }

  function photo(kind, seed) {
    return finish(flat(kind, rng(seed || 7)), seed || 7);
  }

