  var tables = { en: en, es: es, pt: pt, it: it, de: de, fr: fr, nl: nl, ja: ja };

  /** The table code for a device language tag (es-MX, pt_BR, ja-JP...), en for anything else. */
  function resolve(tag) {
    var lang = String(tag || 'en').replace(/_/g, '-').toLowerCase().split('-')[0];
    return Object.prototype.hasOwnProperty.call(tables, lang) ? lang : 'en';
  }

  function lang() {
    try {
      return (typeof navigator !== 'undefined' && navigator.language) || 'en';
    } catch (e) {
      return 'en';
    }
  }

  // A table with English underneath, word by word (lists too), so a missing word never shows as undefined.
  function under(t, base) {
    if (Array.isArray(base)) {
      var list = [];
      for (var i = 0; i < base.length; i++) list.push(Array.isArray(t) && typeof t[i] === typeof base[i] ? t[i] : base[i]);
      return list;
    }
    var out = {};
    var src = t && typeof t === 'object' ? t : {};
    for (var k in base) {
      if (!Object.prototype.hasOwnProperty.call(base, k)) continue;
      var b = base[k];
      if (Array.isArray(b)) out[k] = under(src[k], b);
      else out[k] = typeof src[k] === typeof b ? src[k] : b;
    }
    return out;
  }

  function withFallback(t) {
    return t === en ? en : under(t, en);
  }

  function format(s, vars) {
    return String(s).replace(/\{(\w+)\}/g, function (m, k) { return vars && vars[k] != null ? vars[k] : m; });
  }

  var code = resolve(lang());

  return {
    t: withFallback(tables[code]), code: code, en: en, tables: tables,
    format: format, resolve: resolve, withFallback: withFallback
  };
