  // One table per store listing language, keyed by its Play code.
  var tables = {
    en: en, 'es-419': es419, 'pt-BR': ptBR, 'fr-FR': frFR, 'de-DE': deDE, 'it-IT': itIT, id: id,
    'hi-IN': hiIN, 'ja-JP': jaJP, 'ko-KR': koKR, 'ru-RU': ruRU, 'tr-TR': trTR,
    ur: ur, gu: gu, pa: pa, 'bn-BD': bnBD, 'ne-NP': neNP
  };

  // A device language (its first subtag) to the table that serves it. Every Spanish gets the Latin
  // American table, every Portuguese the Brazilian one, Bengali in India the Bangladesh one; "in" is
  // the code old Android versions report for Indonesian. Anything else (Chinese, say) is English.
  var BY_LANGUAGE = {
    en: 'en', es: 'es-419', pt: 'pt-BR', fr: 'fr-FR', de: 'de-DE', it: 'it-IT', id: 'id', 'in': 'id',
    hi: 'hi-IN', ja: 'ja-JP', ko: 'ko-KR', ru: 'ru-RU', tr: 'tr-TR',
    ur: 'ur', gu: 'gu', pa: 'pa', bn: 'bn-BD', ne: 'ne-NP'
  };
  var RTL = { ur: true };

  /** The table code for a device language tag (hi, hi-IN, pt_PT, pa-Guru-IN...), en for anything else. */
  function resolve(tag) {
    var parts = String(tag || 'en').replace(/_/g, '-').toLowerCase().split('-');
    var lang = parts[0];
    // Punjabi in the Shahmukhi script (Pakistan) is read as Urdu, not Gurmukhi; Hindi in Latin letters
    // (Hinglish) as English.
    if (lang === 'pa' && (parts.indexOf('arab') > 0 || parts.indexOf('pk') > 0)) lang = 'ur';
    if (lang === 'hi' && parts.indexOf('latn') > 0) lang = 'en';
    return Object.prototype.hasOwnProperty.call(BY_LANGUAGE, lang) ? BY_LANGUAGE[lang] : 'en';
  }

  function pick(tag) {
    return tables[resolve(tag)];
  }

  /** ltr or rtl for a table code. */
  function dirOf(code) {
    return RTL[code] ? 'rtl' : 'ltr';
  }

  function lang() {
    try {
      return (typeof navigator !== 'undefined' && navigator.language) || 'en';
    } catch (e) {
      return 'en';
    }
  }

  // A table with English underneath, word by word, inside nested groups and lists too, so a missing
  // word never shows as undefined.
  function under(t, base) {
    if (Array.isArray(base)) {
      var list = [];
      for (var i = 0; i < base.length; i++) list.push(Array.isArray(t) && typeof t[i] === typeof base[i] ? t[i] : base[i]);
      return list;
    }
    if (base && typeof base === 'object') {
      var out = {};
      var src = t && typeof t === 'object' && !Array.isArray(t) ? t : {};
      for (var k in base) {
        if (Object.prototype.hasOwnProperty.call(base, k)) {
          out[k] = Object.prototype.hasOwnProperty.call(src, k) ? under(src[k], base[k]) : base[k];
        }
      }
      return out;
    }
    return typeof t === typeof base ? t : base;
  }

  function withFallback(t) {
    return t === en ? en : under(t, en);
  }

  function format(s, vars) {
    return String(s).replace(/\{(\w+)\}/g, function (m, k) { return vars && vars[k] != null ? vars[k] : m; });
  }

  var code = resolve(lang());

  return {
    t: withFallback(tables[code]), code: code, dir: dirOf(code), en: en, tables: tables,
    format: format, pick: pick, resolve: resolve, dirOf: dirOf, withFallback: withFallback
  };
